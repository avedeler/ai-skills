class CloudWorkflowTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.workspace = self.root / "workspace"
        self.project = self.root / "project"
        self.skills = self.root / "skills"
        self.workspace.mkdir()
        self.project.mkdir()
        self.calls = self.root / "env-calls.jsonl"
        self.cli = self.root / "openspec"
        self._make_cli()

    def _make_cli(self, *, version="1.14.3", context=None, status=None, instructions=None,
                  fail=None, delay=0, malformed=None, path=None, calls=None, change="demo"):
        path = Path(path) if path else self.cli
        calls = Path(calls) if calls else self.calls
        config = {"version": version,
                  "context": context if context is not None else {"root": {"path": str(self.project)}},
                  "status": status if status is not None else {"changeName": change},
                  "instructions": instructions if instructions is not None else {
                      "changeName": change, "state": "ready"},
                  "fail": fail, "delay": delay, "malformed": malformed,
                  "change": change, "calls": str(calls)}
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("#!/usr/bin/env python3\nimport json, os, pathlib, sys, time\n"
                           "c=json.loads(" + repr(json.dumps(config)) + ")\n"
                           "args=sys.argv[1:]\n"
                           "with open(c['calls'], 'a') as f: f.write(json.dumps({'executable':str(pathlib.Path(__file__).resolve()),'argv':args,'cwd':os.getcwd(),'telemetry':os.environ.get('OPENSPEC_TELEMETRY')})+'\\n')\n"
                           "if args == ['--version']: print(c['version']); raise SystemExit(0)\n"
                           "if c['delay']: time.sleep(c['delay'])\n"
                           "if c['fail'] and c['fail'] in args: print('simulated failure', file=sys.stderr); raise SystemExit(9)\n"
                           "if c['malformed'] and c['malformed'] in args: print('{malformed'); raise SystemExit(0)\n"
                           "key='context' if args[:1] == ['context'] else ('status' if args[:1] == ['status'] else 'instructions')\n"
                           "print(json.dumps(c[key]))\n")
        path.chmod(0o755)
        return path

    def install(self):
        cloud.install(self.workspace, self.skills, str(self.cli), "1.14.3")

    def test_fresh_repeat_and_unmanaged_bytes(self):
        unrelated = b"# Existing rules\r\nleave these bytes alone\n"
        (self.workspace / "AGENTS.md").write_bytes(unrelated)
        self.install()
        agents = (self.workspace / "AGENTS.md").read_bytes()
        self.assertTrue(agents.startswith(unrelated))
        router = self.skills / "openspec-model-router"
        team = self.skills / "openspec-development-team"
        self.assertFalse(list(self.skills.rglob("*.pyc")))
        cache = team / "scripts" / "__pycache__"
        cache.mkdir(parents=True, exist_ok=True)
        (cache / "local-cache.pyc").write_bytes(b"generated by Python")
        snapshot = {str(p): p.read_bytes() for base in (router, team)
                    for p in base.rglob("*") if p.is_file() and p.suffix != ".pyc"}
        self.install()
        self.assertEqual((self.workspace / "AGENTS.md").read_bytes(), agents)
        self.assertEqual(snapshot, {str(p): p.read_bytes() for base in (router, team)
                                    for p in base.rglob("*") if p.is_file() and p.suffix != ".pyc"})
        cloud._verify(self.workspace, self.skills, str(self.cli), "1.14.3")
        self.assertEqual((cache / "local-cache.pyc").read_bytes(), b"generated by Python")

    def test_conflict_is_detected_before_any_new_installation(self):
        (self.skills / "openspec-development-team").mkdir(parents=True)
        marker = self.skills / "openspec-development-team" / "user.txt"
        marker.write_text("retain")
        with self.assertRaisesRegex(ValueError, "differs"):
            self.install()
        self.assertFalse((self.skills / "openspec-model-router").exists())
        self.assertFalse((self.workspace / "AGENTS.md").exists())
        self.assertEqual(marker.read_text(), "retain")

    def test_modified_and_malformed_managed_block_refused(self):
        (self.workspace / "AGENTS.md").write_bytes(
            b"unmanaged\n" + cloud._block(self.workspace, self.skills, str(self.cli), "1.14.3") + b"\n")
        self.install()
        path = self.workspace / "AGENTS.md"
        original = path.read_bytes()
        path.write_bytes(original.replace(b"fresh-context", b"changed-context"))
        with self.assertRaisesRegex(ValueError, "managed"):
            self.install()
        self.assertIn(b"changed-context", path.read_bytes())
        path.write_bytes(original + cloud.BEGIN.encode())
        with self.assertRaisesRegex(ValueError, "malformed"):
            self.install()

    def test_missing_or_wrong_cli_prevents_writes(self):
        with self.assertRaisesRegex(ValueError, "not found"):
            cloud.install(self.workspace, self.skills, "no-such-openspec-command-xyz", "1.14.3")
        self.assertFalse(self.skills.exists())
        self._make_cli(version="9.9")
        with self.assertRaisesRegex(ValueError, "prerequisite version mismatch"):
            self.install()
        self.assertFalse(self.skills.exists())

    def test_verify_detects_missing_modified_content_and_version(self):
        self.install()
        (self.skills / "openspec-model-router" / "SKILL.md").write_text("edited")
        with self.assertRaisesRegex(ValueError, "router package/profile"):
            cloud._verify(self.workspace, self.skills, str(self.cli), "1.14.3")
        with self.assertRaisesRegex(ValueError, "version mismatch"):
            # Package mismatch is checked first, so restore canonical bytes to
            # isolate the independently checked executable version.
            import shutil
            shutil.rmtree(self.skills / "openspec-model-router")
            cloud._stage_package(cloud.ROUTER, self.skills / "openspec-model-router",
                                 cloud._router_expected())
