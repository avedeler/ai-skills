    def test_generated_commands_quote_values_and_keep_absolute_paths(self):
        setup = self.root / "setup"
        setup.mkdir()
        odd = "space ' ;$(touch PWNED) {{OPENSPEC_VERSION}}"
        workspace = self.root / ("workspace " + odd)
        skills = self.root / ("skills " + odd)
        project = self.root / ("project " + odd)
        workspace.mkdir()
        project.mkdir()
        other_cwd = self.root / "elsewhere"
        other_cwd.mkdir()
        cli_path = setup / "bin" / ("openspec " + odd)
        change = "change ' ;$(touch PWNED) {{OPENSPEC_VERSION}}"
        calls = self.root / "odd-calls.jsonl"
        self._make_cli(path=cli_path, calls=calls, change=change,
                       context={"root": {"path": str(project)}})
        previous = Path.cwd()
        try:
            os.chdir(setup)
            cloud.install(workspace, skills, "bin/" + cli_path.name, "1.14.3")
        finally:
            os.chdir(previous)
        block = (workspace / "AGENTS.md").read_text()
        self.assertIn("{{OPENSPEC_VERSION}}", block)
        self.assertIn(shlex.quote(str(cli_path.resolve())), block)
        commands = re.findall(r"^python3 .*?(?:verify|preflight).*?$", block, re.MULTILINE)
        self.assertEqual(len(commands), 2)
        verify = subprocess.run(["/bin/sh", "-c", commands[0]], cwd=other_cwd,
                                text=True, capture_output=True)
        self.assertEqual(verify.returncode, 0, verify.stderr)
        preflight_cmd = commands[1].replace("/path/to/selected/project", shlex.quote(str(project)))
        preflight_cmd = preflight_cmd.replace("CHANGE_ID", shlex.quote(change))
        preflight = subprocess.run(["/bin/sh", "-c", preflight_cmd], cwd=other_cwd,
                                   text=True, capture_output=True)
        self.assertEqual(preflight.returncode, 0, preflight.stderr)
        self.assertFalse((other_cwd / "PWNED").exists())
        records = [json.loads(line) for line in calls.read_text().splitlines()]
        self.assertEqual([record["argv"] for record in records], [
            ["--version"], ["--version"], ["--version"], ["--version"], ["context", "--json"],
            ["status", "--change", change, "--json"],
            ["instructions", "apply", "--change", change, "--json"]])
        self.assertEqual([record["cwd"] for record in records],
                         [str(workspace), str(workspace), str(workspace), str(project),
                          str(project), str(project), str(project)])
        self.assertTrue(all(record["telemetry"] == "0" for record in records))
        self.assertEqual(list(project.iterdir()), [])

    def test_project_wrapper_and_version_are_independent(self):
        self.install()
        managed_before = (self.workspace / "AGENTS.md").read_bytes()
        project_cli = self._make_cli(path=self.project / "wrappers" / "openspec",
                                     calls=self.root / "project-calls.jsonl",
                                     version="2.7.0", change="demo")
        before = {p.relative_to(self.project): p.read_bytes() for p in self.project.rglob("*")
                  if p.is_file()}
        cloud.preflight(self.workspace, self.skills, str(self.cli), "1.14.3",
                         self.project, "apply", "demo", "wrappers/openspec", "2.7.0")
        self.assertEqual((self.workspace / "AGENTS.md").read_bytes(), managed_before)
        after = {p.relative_to(self.project): p.read_bytes() for p in self.project.rglob("*")
                 if p.is_file()}
        self.assertEqual(after, before)
        env_calls = [json.loads(line) for line in self.calls.read_text().splitlines()]
        project_calls = [json.loads(line) for line in (self.root / "project-calls.jsonl").read_text().splitlines()]
        self.assertEqual([item["argv"] for item in env_calls], [["--version"], ["--version"]])
        self.assertEqual([item["argv"] for item in project_calls], [
            ["--version"], ["context", "--json"], ["status", "--change", "demo", "--json"],
            ["instructions", "apply", "--change", "demo", "--json"]])
        self.assertTrue(all(item["cwd"] == str(self.project) for item in project_calls))
        self.assertTrue(all(item["executable"] == str(project_cli) for item in project_calls))
        self.assertTrue(all(item["telemetry"] == "0" for item in env_calls + project_calls))

    def _assert_default_cli_calls(self, command, records):
        self.assertEqual([item["argv"] for item in records], [
            ["--version"], ["--version"], ["--version"], ["context", "--json"],
            ["status", "--change", "demo", "--json"],
            ["instructions", "apply", "--change", "demo", "--json"]])
        self.assertEqual([item["cwd"] for item in records],
                         [str(self.workspace)] * 2 + [str(self.project)] * 4)
        self.assertTrue(all(item["executable"] == str(command.resolve()) for item in records))
        self.assertTrue(all(item["telemetry"] == "0" for item in records))

