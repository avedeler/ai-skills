    def test_verification_and_preflight_do_not_change_canonical_sources(self):
        self.install()
        def snapshot():
            roots = [cloud.ADAPTER, cloud.ROUTER, cloud.TEAM]
            result = {}
            for root in roots:
                for path in root.rglob("*"):
                    if "__pycache__" in path.parts or path.suffix in (".pyc", ".pyo"):
                        continue
                    if path.is_file() and not path.is_symlink():
                        result[path.relative_to(cloud.REPOSITORY).as_posix()] = path.read_bytes()
            return result
        before = snapshot()
        cloud._verify(self.workspace, self.skills, str(self.cli), "1.14.3")
        cloud.preflight(self.workspace, self.skills, str(self.cli), "1.14.3",
                        self.project, "apply", "demo")
        self.assertEqual(snapshot(), before)

    def test_instruction_and_ancestor_symlinks_are_rejected_before_writes(self):
        target = self.root / "external-agents"
        target.write_bytes(b"keep this exact content\r\n")
        agents = self.workspace / "AGENTS.md"
        for destination in (target, self.root / "missing-target"):
            if agents.is_symlink() or agents.exists():
                agents.unlink()
            agents.symlink_to(destination)
            with self.assertRaisesRegex(ValueError, "AGENTS.md"):
                self.install()
            self.assertTrue(agents.is_symlink())
            self.assertEqual(target.read_bytes(), b"keep this exact content\r\n")
            self.assertFalse(self.skills.exists())
        if agents.is_symlink():
            agents.unlink()
        real_parent = self.root / "real-parent"
        real_parent.mkdir()
        linked_parent = self.root / "linked-parent"
        linked_parent.symlink_to(real_parent, target_is_directory=True)
        with self.assertRaisesRegex(ValueError, "unsafe destination parent"):
            cloud.install(self.workspace, linked_parent / "skills", str(self.cli), "1.14.3")
        self.assertEqual(list(real_parent.iterdir()), [])
        self.assertFalse((self.workspace / "AGENTS.md").exists())

    def test_nonregular_package_entries_are_rejected_without_reading(self):
        import os
        source = self.root / "source-package"
        source.mkdir()
        (source / "regular.txt").write_text("ok")
        os.mkfifo(source / "unexpected-fifo")
        with self.assertRaisesRegex(ValueError, "nonregular"):
            cloud._inventory(source)
        installed = self.root / "installed-package"
        installed.mkdir()
        (installed / "regular.txt").write_text("ok")
        os.mkfifo(installed / "unexpected-fifo")
        with self.assertRaisesRegex(ValueError, "nonregular"):
            cloud._installed_match(installed, {"regular.txt": b"ok"})


